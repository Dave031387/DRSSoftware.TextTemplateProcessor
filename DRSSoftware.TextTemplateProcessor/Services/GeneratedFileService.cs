namespace DRSSoftware.TextTemplateProcessor.Services;

/// <summary>
/// The <see cref="GeneratedFileService"/> manages the text lines that are generated from the text
/// template file and handles writing those lines to the designated output file.
/// </summary>
internal class GeneratedFileService : DependencyCheckerBase, IGeneratedFileService
{
    /// <summary>
    /// Creates a new instance of the <see cref="GeneratedFileService"/> class and initializes dependencies.
    /// </summary>
    /// <param name="fileAndDirectoryService">
    /// A reference to the file and directory service.
    /// </param>
    /// <param name="logger">
    /// A reference to the logger service.
    /// </param>
    /// <param name="pathValidator">
    /// A reference to the path validator service.
    /// </param>
    internal GeneratedFileService(IFileAndDirectoryService fileAndDirectoryService,
                                  ILogger logger,
                                  IPathValidator pathValidator)
    {
        FileAndDirectoryService = NullDependencyCheck(fileAndDirectoryService, nameof(fileAndDirectoryService));
        Logger = NullDependencyCheck(logger, nameof(logger));
        PathValidator = NullDependencyCheck(pathValidator, nameof(pathValidator));
        OutputFileName = string.Empty;
        OutputFilePath = string.Empty;
        OutputDirectoryPath = string.Empty;
        GeneratedTextLines = [];
    }

    /// <summary>
    /// Gets a value indicating whether or not the generated text file is empty.
    /// </summary>
    public bool IsEmptyFile => GeneratedTextLines.Count is 0;

    /// <summary>
    /// Gets the number of generated text lines that have been added thus far.
    /// </summary>
    public int LineCount => GeneratedTextLines.Count;

    /// <summary>
    /// Gets the directory path where the generated text file will be written to.
    /// </summary>
    public string OutputDirectoryPath
    {
        get;
        private set;
    }

    /// <summary>
    /// Gets the file name of the generated text file.
    /// </summary>
    public string OutputFileName
    {
        get;
        private set;
    }

    /// <summary>
    /// Gets the full file path of the generated text file.
    /// </summary>
    public string OutputFilePath
    {
        get;
        private set;
    }

    /// <summary>
    /// Gets a reference to the file and directory service.
    /// </summary>
    private IFileAndDirectoryService FileAndDirectoryService
    {
        get;
        init;
    }

    /// <summary>
    /// Gets or sets a list of strings representing text lines that have been generated by the text
    /// template processor.
    /// </summary>
    private List<string> GeneratedTextLines
    {
        get;
        set;
    }

    /// <summary>
    /// Gets a reference to the logger service.
    /// </summary>
    private ILogger Logger
    {
        get;
        init;
    }

    /// <summary>
    /// Gets a reference to the path validator service.
    /// </summary>
    private IPathValidator PathValidator
    {
        get;
        init;
    }

    /// <summary>
    /// Add the given <paramref name="text"/> string to the generated text.
    /// </summary>
    /// <param name="text">
    /// The text string to be added to the generated text.
    /// </param>
    public void AddText(string text) => GeneratedTextLines.Add(text);

    /// <summary>
    /// Clears the generated text and sets the output file path and file name to empty strings.
    /// </summary>
    public void Clear()
    {
        GeneratedTextLines.Clear();
        OutputDirectoryPath = string.Empty;
        OutputFileName = string.Empty;
        OutputFilePath = string.Empty;
    }

    /// <summary>
    /// Write the contents of the generated text lines to the given file path.
    /// </summary>
    /// <param name="filePath">
    /// The file path where the generated text lines are to be written.
    /// </param>
    /// <returns>
    /// <see langword="true"/> if the output file was successfully written to; otherwise, <see langword="false"/>
    /// </returns>
    public bool WriteGeneratedText(string filePath)
    {
        bool isValid = false;
        string message = GetMessage(MsgWritingGeneratedTextFile, filePath);

        Logger.Log(LogSeverity.Information, message);

        try
        {
            ValidateOutputFilePath(filePath);

            if (IsEmptyFile)
            {
                message = GetMessage(MsgGeneratedTextIsEmpty);
                Logger.Log(LogSeverity.Error, message);
            }
            else
            {
                CheckForExistingFile();
                FileAndDirectoryService.WriteTextFile(OutputFilePath, GeneratedTextLines);
                message = GetMessage(MsgOutputFileSuccessfullyCreated, GeneratedTextLines.Count.ToString());
                Logger.Log(LogSeverity.Information, message);
                isValid = true;
            }
        }
        catch (Exception ex)
        {
            message = GetMessage(MsgUnableToCreateOutputFile, ex.Message);
            Logger.Log(LogSeverity.Error, message);
        }

        return isValid;
    }

    /// <summary>
    /// Checks to see if the output file already exists and issues a warning message if it does.
    /// Otherwise, it creates the output directory if it doesn't already exist.
    /// </summary>
    private void CheckForExistingFile()
    {
        if (FileAndDirectoryService.FileExists(OutputFilePath))
        {
            string message = GetMessage(MsgOutputFileWillBeOverwritten);
            Logger.Log(LogSeverity.Warning, message);
        }
        else
        {
            _ = FileAndDirectoryService.CreateDirectory(OutputDirectoryPath);
        }
    }

    /// <summary>
    /// Validates that the given <paramref name="filePath"/> is a valid file path and determines the
    /// full path name, file name, and directory path.
    /// </summary>
    /// <param name="filePath">
    /// The file path to be validated.
    /// </param>
    private void ValidateOutputFilePath(string filePath)
    {
        OutputFilePath = PathValidator.ValidatePath(filePath, true);
        OutputFileName = FileAndDirectoryService.GetFileName(OutputFilePath);
        OutputDirectoryPath = FileAndDirectoryService.GetDirectoryName(OutputFilePath);
    }
}